#!/usr/bin/env node
// Generate the schema field reference and the scripts flag reference from source.
//
// Audit finding F-6: "the expert trail dead-ends". To learn every frontmatter
// field a reader was sent to the raw JSON Schema files, and the two skill
// scripts' operational flags, including the security-critical
// --ephemeral-input-file, existed only inside argparse strings in a ~1000-line
// script.
//
// Both pages are GENERATED rather than written, for the same reason the catalog
// pages are: a hand-maintained field list is wrong the first time a schema
// changes, and a hand-maintained flag list is wrong the first time someone adds
// an argument. The schema page reads schemas/*.schema.json; the scripts page
// reads each script's own --help output, so it cannot describe a flag the
// script does not actually have.
//
// Usage:
//   node scripts/gen-reference.mjs            # write into site/src/content/docs/reference
//   node scripts/gen-reference.mjs --check    # exit 1 if the committed pages are stale
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..');
const SCHEMAS = path.join(REPO_ROOT, 'schemas');
const OUT_DIR = path.join(REPO_ROOT, 'site', 'src', 'content', 'docs', 'reference');

const BANNER =
  '<!-- GENERATED by scripts/gen-reference.mjs - do not edit by hand. ' +
  'Edit schemas/*.schema.json or the script argparse definitions and regenerate. -->';

// The two shipped skill scripts. Their flags are read from --help so this page
// can never claim a flag that does not exist.
const SCRIPTS = [
  {
    label: 'recommend.py',
    rel: 'skills/entry-recommender/scripts/recommend.py',
    blurb:
      'Scores the stable catalog against a described situation, per axis. This is a ' +
      'deterministic pre-filter, not the recommendation itself: the pick-and-justify ' +
      'judgment happens in the skill reasoning, using this output as candidate data.',
  },
  {
    label: 'build-instruction.py',
    rel: 'skills/writing-instruction-builder/scripts/build-instruction.py',
    blurb:
      'Composes selected entries into a ready-to-paste prompt prefix, applying the ' +
      'conflict-aware composition rules from ADR 0016.',
  },
];

function schemaFiles() {
  const out = [];
  for (const dirent of fs.readdirSync(SCHEMAS, { withFileTypes: true })) {
    if (dirent.isDirectory()) {
      for (const f of fs.readdirSync(path.join(SCHEMAS, dirent.name))) {
        if (f.endsWith('.schema.json')) out.push(path.join(dirent.name, f));
      }
    } else if (dirent.name.endsWith('.schema.json')) {
      out.push(dirent.name);
    }
  }
  return out.sort();
}

function describeType(prop) {
  if (!prop || typeof prop !== 'object') return '';
  if (prop.enum) return `enum: ${prop.enum.map((v) => `\`${v}\``).join(', ')}`;
  let t = prop.type || (prop.$ref ? 'ref' : '');
  if (Array.isArray(t)) t = t.join(' or ');
  if (t === 'array') {
    const items = prop.items && prop.items.type ? prop.items.type : 'object';
    const bounds = [];
    if (prop.minItems !== undefined) bounds.push(`min ${prop.minItems}`);
    if (prop.maxItems !== undefined) bounds.push(`max ${prop.maxItems}`);
    return `array of ${items}${bounds.length ? ` (${bounds.join(', ')})` : ''}`;
  }
  return t;
}

function renderSchemaPage() {
  const L = [];
  L.push('---');
  L.push('title: Schema reference');
  L.push('description: Every frontmatter field an entry, example, or diff-pair can carry, generated from the JSON Schemas themselves.');
  L.push('---');
  L.push('');
  L.push(BANNER);
  L.push('');
  L.push('Every field the catalog validates, read directly from `schemas/*.schema.json`. This');
  L.push('page is generated, so it cannot drift from what `tools/validate.py` actually enforces.');
  L.push('');
  L.push('The contract is frozen. Before changing any schema, read the change-class policy in');
  L.push('[ADR 0019](https://github.com/product-on-purpose/writing-style-catalog/blob/main/docs/internal/adr/0019-schema-freeze-and-change-policy.md):');
  L.push('annotation edits are a normal PR, a new optional property is a minor bump, and anything');
  L.push('else needs an ADR, a major bump, and a migration.');
  L.push('');

  for (const rel of schemaFiles()) {
    const schema = JSON.parse(fs.readFileSync(path.join(SCHEMAS, rel), 'utf8'));
    const required = new Set(schema.required || []);
    const props = schema.properties || {};
    const frozen = !rel.startsWith('experimental');

    L.push(`## \`${rel}\``);
    L.push('');
    if (schema.description) L.push(`${schema.description}`);
    L.push('');
    L.push(`- **Published at:** \`${schema.$id || '(no $id)'}\``);
    L.push(`- **Freeze status:** ${frozen ? 'frozen (ADR 0019)' : '**not frozen** - may take a breaking change without a major version bump'}`);
    if (schema.allOf) {
      const refs = schema.allOf.filter((a) => a.$ref).map((a) => `\`${a.$ref}\``);
      if (refs.length) L.push(`- **Composes:** ${refs.join(', ')}`);
    }
    L.push('');

    const names = Object.keys(props).sort();
    if (!names.length) {
      L.push('_Adds no properties of its own; see the schema it composes._');
      L.push('');
      continue;
    }
    L.push('| Field | Type | Required | Notes |');
    L.push('| --- | --- | --- | --- |');
    for (const name of names) {
      const p = props[name];
      // Escape for a Markdown table cell. Backslash FIRST, then pipe: doing it
      // the other way round would re-escape the backslashes this step just
      // added, turning an escaped pipe back into a cell break (CodeQL
      // js/incomplete-sanitization). Newlines are already collapsed above,
      // since a literal newline ends the row.
      const desc = (p.description || '')
        .replace(/\s+/g, ' ')
        .replace(/\\/g, '\\\\')
        .replace(/\|/g, '\\|')
        .trim();
      L.push(`| \`${name}\` | ${describeType(p)} | ${required.has(name) ? '**yes**' : 'no'} | ${desc} |`);
    }
    L.push('');
  }
  return L.join('\n') + '\n';
}

function helpText(rel) {
  try {
    return execFileSync('python', [path.join(REPO_ROOT, rel), '--help'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
  } catch (err) {
    // A shipped script must be runnable; a broken --help is a real failure.
    throw new Error(`gen-reference: could not read --help from ${rel}: ${err.message}`);
  }
}

function renderScriptsPage() {
  const L = [];
  L.push('---');
  L.push('title: Scripts reference');
  L.push('description: Every command-line flag of the two shipped skill scripts, generated from their own --help output.');
  L.push('---');
  L.push('');
  L.push(BANNER);
  L.push('');
  L.push('Both shipped scripts, with every flag they accept. Generated from each script\'s own');
  L.push('`--help`, so this page cannot describe an option the script does not have.');
  L.push('');
  L.push('Most readers never need this: the skills drive both scripts themselves. It exists for');
  L.push('running them directly, and for reviewing what the skill is doing on your behalf.');
  L.push('');

  for (const s of SCRIPTS) {
    L.push(`## \`${s.label}\``);
    L.push('');
    L.push(s.blurb);
    L.push('');
    L.push(`Source: [\`${s.rel}\`](https://github.com/product-on-purpose/writing-style-catalog/blob/main/${s.rel})`);
    L.push('');
    L.push('```text');
    L.push(helpText(s.rel).trimEnd());
    L.push('```');
    L.push('');
  }

  L.push('## A note on `--ephemeral-input-file`');
  L.push('');
  L.push('`recommend.py` accepts a situation on stdin or in a file. The ephemeral variant reads');
  L.push('the file and then deletes it, which is why it refuses any path not ending in the');
  L.push('required suffix: a delete-after-read flag pointed at an arbitrary path is a destructive');
  L.push('primitive. The guard is deliberate and should not be relaxed to make a call site more');
  L.push('convenient.');
  L.push('');
  return L.join('\n') + '\n';
}

function referencePages() {
  return {
    'schema.md': renderSchemaPage(),
    'scripts.md': renderScriptsPage(),
  };
}

// Called by gen-site.mjs AFTER it clears the generated subtrees, so these pages
// are not wiped by that clear. Running gen-reference standalone works too; the
// ordering only matters when both run.
export function writeReferencePages() {
  const pages = referencePages();
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const [name, body] of Object.entries(pages)) {
    fs.writeFileSync(path.join(OUT_DIR, name), body);
  }
  return Object.keys(pages).length;
}

function main() {
  const check = process.argv.includes('--check');
  const pages = referencePages();
  fs.mkdirSync(OUT_DIR, { recursive: true });

  let stale = [];
  for (const [name, body] of Object.entries(pages)) {
    const target = path.join(OUT_DIR, name);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (check) {
      if (current !== body) stale.push(name);
    } else {
      fs.writeFileSync(target, body);
      console.log(`[OK] wrote reference/${name}`);
    }
  }
  if (check) {
    if (stale.length) {
      console.error(`[STALE] ${stale.join(', ')} - run: node scripts/gen-reference.mjs`);
      process.exit(1);
    }
    console.log('[OK] generated reference pages are current');
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  main();
}
